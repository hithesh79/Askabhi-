def term(text, tip):
    """Add an accessible browser tooltip to a technical term."""
    html_block(f'<span title="{html.escape(str(tip), quote=True)}" tabindex="0" style="text-decoration:underline dotted;cursor:help">{html.escape(str(text))}</span>')


@contextmanager
def safe_section(name):
    """Contain page failures and provide non-sensitive context to the user."""
    try:
        yield
    except Exception as exc:
        st.error(f"{name} could not finish this calculation. Your other pages are still available.")
        with st.expander("Technical details"):
            st.code(f"{type(exc).__name__}: {exc}")
