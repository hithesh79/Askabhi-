_ASSET_DIR = Path(__file__).resolve().parents[1] / "assets"


def owl_data_uri() -> str:
    """Return the bundled Abhi Rocket mascot image as a data URI, with fallback to SVG."""
    mascot_path = _ASSET_DIR / "abhi_mascot.jpg"
    if mascot_path.exists():
        raw = mascot_path.read_bytes()
        return "data:image/jpeg;base64," + base64.b64encode(raw).decode("ascii")
    svg_path = _ASSET_DIR / "abhi_owl.svg"
    svg = svg_path.read_text(encoding="utf-8")
    return "data:image/svg+xml;base64," + base64.b64encode(svg.encode("utf-8")).decode("ascii")


def owl_hero_uri() -> str:
    """Return the 3D Abhi Rocket portrait for onboarding & hero."""
    hero_path = _ASSET_DIR / "abhi_hero.jpg"
    if hero_path.exists():
        return "data:image/jpeg;base64," + base64.b64encode(hero_path.read_bytes()).decode("ascii")
    return owl_data_uri()


# Modern Rocket Aliases
rocket_data_uri = owl_data_uri
