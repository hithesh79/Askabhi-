def verdict_banner(tone, headline, sub="", action=None):
    """Show an accessible conclusion-first verdict and its next step."""
    kinds = {
        "success": ("✓", "#83F0A5"),
        "warning": ("⚠", "#FFD166"),
        "danger": ("!", "#FF8585"),
        "info": ("✦", "#B7FF72"),
    }
    icon, color = kinds.get(tone, kinds["info"])
    html_block(f"""
    <div class="ab-card ab-verdict" style="border-left-color:{color}">
      <div class="ab-card-title">{icon} {html.escape(str(headline))}</div>
      <div class="ab-card-sub">{html.escape(str(sub))}</div>
    </div>
    """)
    if action:
        st.caption(f"Suggested next step: {action}")


def kpi_card(label, value, delta=None, hint=None, spark=None):
    """Render a compact KPI using the shared Streamlit theme."""
    with st.container(border=True):
        st.caption(label)
        st.markdown(f"### {value}")
        if delta is not None:
            st.caption(delta)
        if hint:
            st.caption(hint)
        if spark is not None:
            st.caption("Trend is illustrative unless supported by transaction history.")


