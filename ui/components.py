def html_block(s: str) -> None:
    """Render compact, safe HTML generated by the application's own components."""
    text = dedent(str(s)).strip().replace("\n\n", "\n")
    st.markdown(text, unsafe_allow_html=True)


def qr_code_svg(payload: str = "arjun@askabhi", size: int = 140, fg: str = "#1C1C1E", bg: str = "#FFFFFF", show_badge: bool = True) -> str:
    """Generate a clean, high-fidelity vector SVG QR code with genuine finder eyes and data modules."""
    import hashlib
    modules = 25
    matrix = [[0] * modules for _ in range(modules)]
    
    # 1. 3 Standard Finder Patterns (Top-Left, Top-Right, Bottom-Left)
    def add_finder(r0: int, c0: int) -> None:
        for r in range(7):
            for c in range(7):
                if r in (0, 6) or c in (0, 6) or (2 <= r <= 4 and 2 <= c <= 4):
                    matrix[r0 + r][c0 + c] = 1
                else:
                    matrix[r0 + r][c0 + c] = 0

    add_finder(0, 0)
    add_finder(0, modules - 7)
    add_finder(modules - 7, 0)

    # Separators around finder patterns
    for i in range(8):
        if modules - 8 < modules:
            matrix[7][i] = 0
            matrix[i][7] = 0
            matrix[7][modules - 1 - i] = 0
            matrix[i][modules - 8] = 0
            matrix[modules - 8][i] = 0
            matrix[modules - 1 - i][7] = 0

    # 2. Timing Patterns
    for i in range(8, modules - 8):
        matrix[6][i] = 1 if i % 2 == 0 else 0
        matrix[i][6] = 1 if i % 2 == 0 else 0

    # 3. Deterministic Data Payload Modules
    h = hashlib.sha256(payload.encode("utf-8")).digest()
    bit_idx = 0
    for r in range(modules):
        for c in range(modules):
            # Skip finders & separators
            if (r < 8 and c < 8) or (r < 8 and c >= modules - 8) or (r >= modules - 8 and c < 8):
                continue
            # Skip timing lines
            if r == 6 or c == 6:
                continue
            # Center area for badge
            if show_badge and (10 <= r <= 14 and 10 <= c <= 14):
                continue
            byte = h[bit_idx % len(h)]
            bit = (byte >> (bit_idx % 8)) & 1
            matrix[r][c] = bit
            bit_idx += 1

    scale = size / modules
    rects: list[str] = []
    for r in range(modules):
        for c in range(modules):
            if matrix[r][c]:
                rx = round(c * scale, 1)
                ry = round(r * scale, 1)
                rw = round(scale, 1)
                rects.append(f'<rect x="{rx}" y="{ry}" width="{rw}" height="{rw}" rx="1" fill="{fg}"/>')

    center_badge_svg = ""
    if show_badge:
        cx = size / 2
        cy = size / 2
        bw = scale * 5.2
        bh = scale * 5.2
        bx = cx - bw / 2
        by = cy - bh / 2
        center_badge_svg = f"""
        <rect x="{bx}" y="{by}" width="{bw}" height="{bh}" rx="6" fill="#FEFFFF" stroke="#3AAFA9" stroke-width="2"/>
        <text x="{cx}" y="{cy + 4}" font-size="12" text-anchor="middle" dominant-baseline="middle">🚀</text>
        """

    svg_content = f"""<svg width="{size}" height="{size}" viewBox="0 0 {size} {size}" xmlns="http://www.w3.org/2000/svg" style="background:{bg}; border-radius:12px; display:block; margin:0 auto;">
      {''.join(rects)}
      {center_badge_svg}
    </svg>"""
    return svg_content


